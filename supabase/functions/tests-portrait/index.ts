// The Composite Portrait — the flagship paid SKU of the tests funnel
// (docs/tests-monetization.md §4, §6, §8): one six-chapter report built from
// the intersections of every test the account has completed. The portrait
// belongs to the ACCOUNT, not a session — the caller's JWT is the authority
// here, unlike the other funnels where a bare session UUID is the capability.
//
// Money flow mirrors the quiz/photo reports: cache → gate → spend → generate
// → cache. The idempotency key is portrait:{user_id}:{sha256 of the sorted
// participating session ids} — the same composition is never charged twice
// (both languages and retries ride one spend), while a newly completed test or
// a retake changes the composition and honestly opens a new purchase.
//
// Э7 exit criterion (§6): every participating session is re-scored here from
// its raw answers — stored client-computed outcome/scale_totals are never
// trusted in a paid operation. The recomputed numbers are written back so the
// data self-heals, and only then summed (once) into the cross-test scale layer.
