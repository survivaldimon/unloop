interface StoredOutcome {
  factorPercentages?: Record<string, number>;
  profileId?: string | null;
  typeCode?: string;
}

interface SessionRow {
  id: string;
  test_id: string;
  answers: TestAnswers;
  outcome: StoredOutcome | null;
  completed_at: string;
}

const secretCache = new Map<string, string>();

async function getSecret(
  admin: ReturnType<typeof createClient>,
  name: string,
): Promise<string | null> {
  const cached = secretCache.get(name);
  if (cached) return cached;
  const envValue = Deno.env.get(name);
  if (envValue) {
    secretCache.set(name, envValue);
    return envValue;
  }
  const { data, error } = await admin.rpc("unloop_get_secret", { secret_name: name });
  if (error || typeof data !== "string" || !data) return null;
  secretCache.set(name, data);
  return data;
}

async function sha256Hex(input: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(input));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function isCompletePortrait(value: unknown): value is Record<(typeof CHAPTER_KEYS)[number], string> {
  return (
    typeof value === "object" &&
    value !== null &&
    CHAPTER_KEYS.every((key) => typeof (value as Record<string, unknown>)[key] === "string")
  );
}

/**
 * §6: recomputation vs stored client result, compared on profileId and factor
 * percentages with rounding tolerance (both sides round to one decimal, so a
 * real difference is at least a full tenth). A divergence is either engine
 * drift after weight edits (expected, healed by the writeback) or a forged
 * client result (interesting as a signal).
 */
function outcomeDiverges(stored: StoredOutcome, fresh: TestOutcome): boolean {
  if ((stored.profileId ?? null) !== fresh.profileId) return true;
  if ((stored.typeCode ?? null) !== (fresh.typeCode ?? null)) return true;
  const factorIds = new Set([
    ...Object.keys(stored.factorPercentages ?? {}),
    ...Object.keys(fresh.factorPercentages),
  ]);
  for (const id of factorIds) {
    const a = Number(stored.factorPercentages?.[id] ?? NaN);
    const b = fresh.factorPercentages[id] ?? NaN;
    if (!Number.isFinite(a) || !Number.isFinite(b) || Math.abs(a - b) > 0.11) return true;
  }
  return false;
}

Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  const json = (body: unknown, status = 200) =>
    new Response(JSON.stringify(body), {
      status,
      headers: { ...CORS, "Content-Type": "application/json" },
    });

  try {
    // The only input is the language — the composition is derived server-side
    // from the account's sessions, so an empty body simply means English.
    const body = await req.json().catch(() => ({}));
    const lang: Lang = body?.lang === "ru" ? "ru" : "en";

    const admin = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
    );

    // Credits-only SKU: there is no legacy boolean payment for the portrait.
    const enabled = ((await getSecret(admin, "CREDITS_ENABLED")) ?? "").toLowerCase() === "true";
    if (!enabled) return json({ error: "credits_disabled" }, 503);

    // The portrait belongs to the account (§8): the caller's JWT names the
    // owner. The anon key resolves to no user — a portrait needs an account.
    const auth = req.headers.get("authorization") ?? "";
    const jwt = auth.startsWith("Bearer ") ? auth.slice(7) : "";
    const { data: userData } = jwt ? await admin.auth.getUser(jwt) : { data: { user: null } };
    const userId = userData?.user?.id ?? null;
    if (!userId) return json({ error: "sign_in_required" }, 401);

    // Latest completed session per test — the same distinct-on semantics as
    // looplore_test_scale_profile, but through the service role and with the
    // raw answers the recomputation needs.
    const { data: rows, error: rowsError } = await admin
      .from("looplore_test_sessions")
      .select("id, test_id, answers, outcome, completed_at")
      .eq("user_id", userId)
      .not("completed_at", "is", null)
      .order("completed_at", { ascending: false });
    if (rowsError) {
      console.error("tests-portrait sessions", rowsError);
      return json({ error: "internal" }, 500);
    }

    const latest = new Map<string, SessionRow>();
    for (const row of rows ?? []) {
      // Only sessions the engine can honestly re-score count toward the
      // portrait: a known test and a non-empty answer map. Anything else is
      // unusable for a paid recomputation (§6) — skipped, never trusted.
      if (latest.has(row.test_id) || !(row.test_id in TESTS)) continue;
      if (
        !row.answers ||
        typeof row.answers !== "object" ||
        Array.isArray(row.answers) ||
        Object.keys(row.answers).length === 0
      ) {
        continue;
      }
      latest.set(row.test_id, row as SessionRow);
    }

    const sessions = [...latest.values()];
    if (sessions.length < PORTRAIT_GATE) {
      return json({ error: "gate", completed: sessions.length, required: PORTRAIT_GATE }, 403);
    }

    // Composition key: the sorted participating session ids. The same set
    // yields the same hash — cached portrait, duplicate (free) spend; a new
    // test or a retake changes the set and starts a fresh purchase. No
    // language in the key: both languages of one composition share one spend.
    const setHash = await sha256Hex(sessions.map((s) => s.id).sort().join("+"));

    const testsMeta = sessions
      .map((s) => ({ test_id: s.test_id, completed_at: s.completed_at }))
      .sort((a, b) => (a.completed_at < b.completed_at ? 1 : -1));

    // Cache: looplore_portraits, created by the А1 tests-monetization
    // migration (unique on user_id + set_hash). A cached language is already
    // paid for — serve it without touching the ledger or the session rows.
    const { data: cacheRow } = await admin
      .from("looplore_portraits")
      .select("report, created_at")
      .eq("user_id", userId)
      .eq("set_hash", setHash)
      .maybeSingle();
    const cachedPortrait = (cacheRow?.report as Record<string, unknown> | null)?.[lang];
    if (isCompletePortrait(cachedPortrait)) {
      return json({
        portrait: cachedPortrait,
        tests: testsMeta,
        set_hash: setHash,
        created_at: cacheRow?.created_at ?? null,
        cached: true,
      });
    }

    // §6: re-score every session from raw answers and write the result back —
    // outcome, scale_totals and engine_version self-heal on every paid
    // operation. The writeback is best-effort: a failed update is logged and
    // must not block a paid portrait.
    const recomputed: Array<{ session: SessionRow; outcome: TestOutcome }> = [];
    for (const session of sessions) {
      const outcome = scoreTest(TESTS[session.test_id], session.answers);

      if (session.outcome && outcomeDiverges(session.outcome, outcome)) {
        // §6 wants divergence visible; the function log is where server-side
        // signals live (PostHog capture stays client-side in this codebase).
        console.log(
          "test_outcome_mismatch",
          JSON.stringify({
            session_id: session.id,
            test_id: session.test_id,
            stored_profile: session.outcome.profileId ?? null,
            recomputed_profile: outcome.profileId,
          }),
        );
      }

      const { error: writebackError } = await admin
        .from("looplore_test_sessions")
        .update({
          outcome: {
            factorPercentages: outcome.factorPercentages,
            scaleScores: outcome.scaleScores,
            profileId: outcome.profileId,
            ...(outcome.typeCode ? { typeCode: outcome.typeCode } : {}),
          },
          scale_totals: outcome.scaleTotals,
          engine_version: ENGINE_VERSION,
          updated_at: new Date().toISOString(),
        })
        .eq("id", session.id);
      if (writebackError) console.error("tests-portrait writeback", session.id, writebackError);

      recomputed.push({ session, outcome });
    }

    // Sum the recomputed sufficient statistics across tests, normalize ONCE —
    // the same arithmetic as looplore_test_scale_profile, but over verified
    // numbers (§6). Per-test normalized values are kept alongside so the
    // prompt can show how one scale reads in different tests.
    const combinedTotals: ScaleTotals = {};
    const perTestScores = new Map<string, Record<string, number>>();
    for (const { session, outcome } of recomputed) {
      for (const [scale, [weighted, maxWeighted]] of Object.entries(outcome.scaleTotals)) {
        const prev = combinedTotals[scale] ?? [0, 0];
        combinedTotals[scale] = [prev[0] + weighted, prev[1] + maxWeighted];
        let byTest = perTestScores.get(scale);
        if (!byTest) {
          byTest = {};
          perTestScores.set(scale, byTest);
        }
        byTest[session.test_id] = outcome.scaleScores[scale] ?? 0;
      }
    }
    const combinedScores = normalizeScaleTotals(combinedTotals);

    // Prompt aggregates (§4): per-test profile + factor percentages + type
    // code, cross-test scales with per-test values (scales living in 2+ tests
    // are the portrait's core), a few loud single-test scales, and the untaken
    // tests for the closing bridge. Raw answers stay out — 15K+ tokens of
    // noise the recomputation has already digested.
    const titleOf = (testId: string) => TESTS[testId].title[lang];

    const testsPayload = recomputed.map(({ session, outcome }) => {
      const test = TESTS[session.test_id];
      const profile = outcome.profileId ? test.profiles[outcome.profileId] : undefined;
      return {
        test: test.title[lang],
        profile: profile?.name[lang] ?? null,
        profile_id: outcome.profileId,
        ...(outcome.typeCode ? { type_code: outcome.typeCode } : {}),
        factor_percentages: Object.fromEntries(
          Object.entries(outcome.factorPercentages).map(([id, pct]) => [
            test.factorNames[id]?.[lang] ?? id,
            pct,
          ]),
        ),
        taken_on: session.completed_at.slice(0, 10),
      };
    });

    const sharedScales = [...perTestScores.entries()]
      .filter(([, byTest]) => Object.keys(byTest).length >= 2)
      .map(([scale, byTest]) => ({
        scale,
        score: combinedScores[scale] ?? 0,
        by_test: Object.fromEntries(
          Object.entries(byTest).map(([testId, value]) => [titleOf(testId), value]),
        ),
      }))
      .sort((a, b) => Math.abs(b.score - 50) - Math.abs(a.score - 50))
      .slice(0, 18);

    const singles = [...perTestScores.entries()]
      .filter(([, byTest]) => Object.keys(byTest).length === 1)
      .map(([scale, byTest]) => ({
        scale,
        score: combinedScores[scale] ?? 0,
        test: titleOf(Object.keys(byTest)[0]),
      }))
      .sort((a, b) => b.score - a.score);
    // Top and bottom four, deduped when fewer than eight singles exist.
    const notableSingles = [
      ...new Map([...singles.slice(0, 4), ...singles.slice(-4)].map((s) => [s.scale, s])).values(),
    ];

    const takenIds = new Set(recomputed.map(({ session }) => session.test_id));
    const testsNotTaken = CATALOGUE.filter((t) => !takenIds.has(t.id)).map((t) => t.title[lang]);

    const portraitInput = {
      tests_taken: testsPayload,
      cross_test_scales: sharedScales,
      notable_single_test_scales: notableSingles,
      tests_not_taken: testsNotTaken,
    };

    // Spend after the cache miss, before generation. The idempotency key makes
    // client retries, a crash between spend and cache write, and the second
    // language all free (duplicate spends return ok without a new debit).
    const spend = await admin.rpc("credits_spend", {
      p_user_id: userId,
      p_amount: CREDIT_COSTS.portrait,
      p_kind: "spend_portrait",
      p_key: `portrait:${userId}:${setHash}`,
      p_ref: setHash,
      p_meta: null,
    });
    if (spend.error || spend.data?.ok !== true) {
      const balance = typeof spend.data?.balance === "number" ? spend.data.balance : 0;
      return json({ error: "payment_required", balance }, 402);
    }

    const apiKey = await getSecret(admin, "ANTHROPIC_API_KEY");
    if (!apiKey) return json({ error: "llm_not_configured" }, 500);
    const anthropic = new Anthropic({ apiKey });

    const response = await anthropic.messages.create({
      model: REPORT_MODEL,
      // Six chapters at 800-1000 words; RU runs well over EN in tokens.
      max_tokens: 4000,
      // Left on, thinking would share the budget with the chapters and can
      // truncate the JSON (same reasoning as the other sonnet calls).
      thinking: { type: "disabled" },
      system: SYSTEM_BASE + LANG_SUFFIX[lang],
      output_config: { format: { type: "json_schema", schema: PORTRAIT_SCHEMA } },
      messages: [
        {
          role: "user",
          content: `Write the six chapters of the composite portrait for this person:\n${JSON.stringify(portraitInput, null, 2)}`,
        },
      ],
    });

    if (response.stop_reason === "refusal") {
      return json({ error: "generation_declined" }, 500);
    }
    const textBlock = response.content.find((b: { type: string }) => b.type === "text");
    if (!textBlock) return json({ error: "empty_response" }, 500);
    const portrait = JSON.parse((textBlock as { text: string }).text);

    // Both languages of one composition live in one row. The spend already
    // landed — a failed cache write must not eat the portrait; the next call
    // simply regenerates for free on the duplicate key.
    const mergedReport = { ...((cacheRow?.report as Record<string, unknown>) ?? {}), [lang]: portrait };
    const { error: saveError } = await admin
      .from("looplore_portraits")
      .upsert(
        { user_id: userId, set_hash: setHash, report: mergedReport, engine_version: ENGINE_VERSION },
        { onConflict: "user_id,set_hash" },
      );
    if (saveError) console.error("tests-portrait save", saveError);

    return json({
      portrait,
      tests: testsMeta,
      set_hash: setHash,
      created_at: cacheRow?.created_at ?? new Date().toISOString(),
      cached: false,
    });
  } catch (err) {
    console.error("tests-portrait error", err);
    return json({ error: "internal" }, 500);
  }
});
